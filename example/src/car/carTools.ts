type Args = Record<string, any>;
/** summary: the card's short line; say: the sentence the user hears (2026-11-10: what was done, not "Done"). */
type Outcome = { summary: string; result: Record<string, unknown>; say?: string };
type Handler = (args: Args) => Outcome;

/** The car card speaks the app's language (Brazilian Portuguese for the VW demo). */
const pt = () => getTTSLanguage() === 'pt-BR';
const L = (en: string, ptText: string) => (pt() ? ptText : en);

const lang = (): Lang => (pt() ? 'pt-BR' : 'en');

/** Refused by the app: nothing changes; the message is a full sentence the user hears (the turn ends there). */
class Refused extends Error {}

