/** The positions a window / door argument means in this car (steering-wheel side from the vehicle configuration). */
function positions(target: unknown, obj: Obj): Pos[] {
  const p = resolve(target, getCarState().vehicle.steering);
  if (!p) throw new Refused(L(`I don't know which ${obj} that is. Which one do you mean?`, `Não sei qual ${obj === 'door' ? 'porta' : 'vidro'} é esse. Qual você quer?`));
  return p;
}
const nm = (target: unknown, obj: Obj): Name => name(target, obj, lang());
const degrees = (t: number, unit?: string) => `${pt() ? String(t).replace('.', ',') : t}°${unit === 'fahrenheit' ? 'F' : 'C'}`;

/** Not while the car moves (the demo's Parked / Driving switch). */
const NOT_WHILE_DRIVING: Record<string, (args: Args) => boolean> = {
  set_trunk: () => true,
  set_charge_port: () => true,
  rotate_screen: () => true,
  activate_scenario: (a) => a.mode === 'car_wash' || a.mode === 'rest',
  set_window: (a) => (a.window ?? 'all') === 'all' && a.position === 'open',
  open_door: () => true,
};

function range(value: unknown, min: number, max: number, what: string): number {
  const n = Number(value);
  if (!Number.isFinite(n) || n < min || n > max) throw new Refused(L(`I didn't change it: ${what.toLowerCase()} must be between ${min} and ${max}.`, `Não mudei: ${what.toLowerCase()} precisa ficar entre ${min} e ${max}.`));
  return n;
}

