#!/usr/bin/env node
// Turns language_packs.json into src/tts/languagePacks.generated.ts.
//
// Metro only bundles files that appear in a static require(), so the JSON cannot pick the bundled
// languages at runtime: this script writes the require()s of the `bundled` languages (and the file
// table of every language) into a TS file. metro.config.js calls it on every bundle (dev server,
// Android release, iOS), so editing the JSON is all it takes. The file is rewritten only when it changes.
//
//   node scripts/generate-language-packs.js            regenerate (fails on a bad config)
//   node scripts/generate-language-packs.js --rehash   also refresh bytes + sha256 from assets/models/
//
// The same script runs in the Expo app (expo/scripts/, keep the two files identical). Its JSON sets "nativeModelsDir"
// (assets/models/local): Expo's config plugin (plugins/withDaVoiceNativeAssets.js) copies that folder into the native app,
// so a bundled TTS model is referenced by its file name there instead of a require() (Metro would ship it a second time).
// Voice-cloning embedders are always require()d from assets/models/.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const CONFIG = path.join(ROOT, 'language_packs.json');
const MODELS_DIR = path.join(ROOT, 'assets', 'models');
const OUT = path.join(ROOT, 'src', 'tts', 'languagePacks.generated.ts');
// The app's language ids (AppLanguage in src/appflow.ts).
const KNOWN = ['en', 'pt-BR', 'pt-PT', 'de', 'es', 'fr', 'it', 'nl', 'he', 'da', 'sv', 'el'];
const KINDS = ['model', 'embedder'];

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function generate({ rehash = false, quiet = false } = {}) {
  const config = JSON.parse(fs.readFileSync(CONFIG, 'utf8'));
  const errors = [];
  const languages = config.languages || {};
  const bundled = config.bundled || [];
  const baseUrl = String(config.baseUrl || '').replace(/\/+$/, '');
  const nativeModelsDir = config.nativeModelsDir ? path.join(ROOT, config.nativeModelsDir) : null;
  // Where a bundled file must be: the model in nativeModelsDir (Expo) or assets/models/, the embedder in assets/models/.
  const bundledDir = (kind) => (kind === 'model' && nativeModelsDir ? nativeModelsDir : MODELS_DIR);

  for (const id of Object.keys(languages)) {
    if (!KNOWN.includes(id)) errors.push(`unknown language "${id}" (known: ${KNOWN.join(', ')})`);
    for (const kind of KINDS) {
      const f = languages[id][kind];
      if (!f || !f.file) {
        errors.push(`${id}.${kind}: missing "file"`);
        continue;
      }
      const local = path.join(bundledDir(kind), f.file);
      if (rehash) {
        if (!fs.existsSync(local)) errors.push(`${id}.${kind}: --rehash needs ${local}`);
        else {
          f.bytes = fs.statSync(local).size;
          f.sha256 = sha256(local);
        }
      }
      if (!Number.isInteger(f.bytes) || f.bytes <= 0) errors.push(`${id}.${kind}: bad "bytes"`);
      if (!/^[0-9a-f]{64}$/.test(f.sha256 || '')) errors.push(`${id}.${kind}: bad "sha256"`);
    }
  }
  for (const id of bundled) {
    if (!languages[id]) {
      errors.push(`bundled "${id}" has no entry in "languages"`);
      continue;
    }
    for (const kind of KINDS) {
      const f = languages[id][kind];
      if (!f || !f.file) continue;
      const local = path.join(bundledDir(kind), f.file);
      if (!fs.existsSync(local)) errors.push(`bundled ${id}.${kind}: ${local} not found`);
      else if (fs.statSync(local).size !== f.bytes) {
        errors.push(`bundled ${id}.${kind}: ${f.file} is ${fs.statSync(local).size} bytes, config says ${f.bytes} (run with --rehash?)`);
      }
    }
  }
  if (errors.length) {
    throw new Error(`language_packs.json is invalid:\n  - ${errors.join('\n  - ')}`);
  }
  if (rehash) fs.writeFileSync(CONFIG, JSON.stringify(config, null, 2) + '\n');

  const q = JSON.stringify;
  const lines = [];
  lines.push('// GENERATED by scripts/generate-language-packs.js from language_packs.json. Do not edit: edit the JSON.');
  lines.push("import type { AppLanguage } from '../appflow';");
  lines.push('');
  lines.push('export type LanguagePackFile = { filename: string; sizeBytes: number; sha256: string };');
  lines.push('export type LanguagePackFiles = { model: LanguagePackFile; embedder: LanguagePackFile };');
  lines.push('');
  lines.push('/** Where the files are hosted (baseUrl/<filename>); empty until the upload is verified. */');
  lines.push(`export const LANGUAGE_PACK_BASE_URL = ${q(baseUrl)};`);
  lines.push('');
  lines.push('/** The languages built into the app. */');
  lines.push(`export const BUNDLED_LANGUAGES: AppLanguage[] = ${q(bundled)};`);
  lines.push('');
  lines.push('/** The files of every language (bundled or downloaded). */');
  lines.push('export const LANGUAGE_FILES: Partial<Record<AppLanguage, LanguagePackFiles>> = {');
  for (const id of Object.keys(languages)) {
    lines.push(`  ${q(id)}: {`);
    for (const kind of KINDS) {
      const f = languages[id][kind];
      lines.push(`    ${kind}: { filename: ${q(f.file)}, sizeBytes: ${f.bytes}, sha256: ${q(f.sha256)} },`);
    }
    lines.push('  },');
  }
  lines.push('};');
  lines.push('');
  lines.push(nativeModelsDir
    ? `/** The bundled files: models by file name (in the native app, from ${config.nativeModelsDir}), embedders by require(). */`
    : '/** The bundled files (static require()s, so Metro ships exactly these). */');
  lines.push('export const BUNDLED_LANGUAGE_FILES: Partial<Record<AppLanguage, { model: any; embedder: any }>> = {');
  for (const id of bundled) {
    lines.push(`  ${q(id)}: {`);
    for (const kind of KINDS) {
      const file = languages[id][kind].file;
      lines.push(kind === 'model' && nativeModelsDir
        ? `    ${kind}: ${q(file)},`
        : `    ${kind}: require('../../assets/models/${file}'),`);
    }
    lines.push('  },');
  }
  lines.push('};');
  const text = lines.join('\n') + '\n';

  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (old !== text) {
    fs.writeFileSync(OUT, text);
    if (!quiet) console.log(`[language packs] wrote ${path.relative(ROOT, OUT)}: bundled ${bundled.join(', ') || '(none)'}`);
  }
  return { bundled, downloaded: Object.keys(languages).filter((id) => !bundled.includes(id)) };
}

module.exports = { generate };

if (require.main === module) {
  try {
    const { bundled, downloaded } = generate({ rehash: process.argv.includes('--rehash') });
    console.log(`bundled: ${bundled.join(', ') || '(none)'}`);
    console.log(`downloaded: ${downloaded.join(', ') || '(none)'}`);
  } catch (e) {
    console.error(String(e.message || e));
    process.exit(1);
  }
}
